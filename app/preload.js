const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('flux', {
  min: () => ipcRenderer.send('win:min'),
  fit: (size) => ipcRenderer.send('win:fit', size),
  copy: (t) => ipcRenderer.invoke('clipboard:write', t),
  bridgeLoader: () => ipcRenderer.invoke('bridge:loader'),
  bridgeState: () => ipcRenderer.invoke('bridge:state'),
  bridgeSend: (c) => ipcRenderer.invoke('bridge:send', c),
  claudeChats: () => ipcRenderer.invoke('claude:chats'),
  claudeHistory: (id) => ipcRenderer.invoke('claude:history', id),
  claudeSend: (d) => ipcRenderer.invoke('claude:send', d),
  claudeStop: (k) => ipcRenderer.invoke('claude:stop', k),
  claudeAuth: () => ipcRenderer.invoke('claude:auth'),
  claudePickDir: () => ipcRenderer.invoke('claude:pickDir'),
  claudeHome: () => ipcRenderer.invoke('claude:home'),
  onClaude: (cb) => ipcRenderer.on('claude:line', (_e, k, o) => cb(k, o)),
  claudeUsage: () => ipcRenderer.invoke('claude:usage'),
  onClaudeUsage: (cb) => ipcRenderer.on('claude:usage', (_e, u) => cb(u)),
  aiList: () => ipcRenderer.invoke('ai:list'),
  aiAdd: (d) => ipcRenderer.invoke('ai:add', d),
  aiRemove: (id) => ipcRenderer.invoke('ai:remove', id),
  reportFeatures: (f) => ipcRenderer.send('app:features', f),
  onClaudeChanged: (cb) => ipcRenderer.on('claude:changed', (_e, ids) => cb(ids)),
  workspaceGet: () => ipcRenderer.invoke('workspace:get'),
  workspacePick: () => ipcRenderer.invoke('workspace:pick'),
  toggleFullscreen: () => ipcRenderer.send('win:fullscreen'),
  quit: () => ipcRenderer.send('win:quit'),
  onCloseRequest: (cb) => ipcRenderer.on('win:closeRequest', () => cb()),
  lanIp: () => ipcRenderer.invoke('net:lanIp'),
  open: (url) => ipcRenderer.send('open', url),
  hostStart: (cfg) => ipcRenderer.invoke('host:start', cfg),
  hostStop: () => ipcRenderer.invoke('host:stop'),
  hostFix: (kind, method) => ipcRenderer.invoke('host:fix', { kind, method }),
  hostRetry: (method) => ipcRenderer.invoke('host:retry', method),
  hostRunning: () => ipcRenderer.invoke('host:running'),
  onHost: (cb) => ipcRenderer.on('host:event', (_e, m) => cb(m)),
  version: () => ipcRenderer.invoke('app:version'),
  scriptsList: () => ipcRenderer.invoke('scripts:list'),
  scriptsRead: (n) => ipcRenderer.invoke('scripts:read', n),
  scriptsWrite: (n, t) => ipcRenderer.invoke('scripts:write', n, t),
  scriptsDelete: (n) => ipcRenderer.invoke('scripts:delete', n),
  monacoEnsure: () => ipcRenderer.invoke('monaco:ensure'),
  cores: () => ipcRenderer.invoke('app:cores'),
  isFullscreen: () => ipcRenderer.invoke('win:isFullscreen'),
  onFullscreen: (cb) => ipcRenderer.on('fullscreen', (_e, on) => cb(!!on)),
});
